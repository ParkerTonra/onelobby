#!/usr/bin/env node
// Generates docs/api/js.md and docs/api/dotnet.md from the real client sources.
//   JS:     tsc --emitDeclarationOnly on clients/js/packages/client (the .d.ts the package ships), public modules only.
//   .NET:   public signatures + /// summaries scanned from clients/dotnet/Keepalive.Core and Keepalive.Godot.
// Deterministic: LF endings, sorted paths, no timestamps. Run `node docs/build.mjs` and commit docs/api/.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "docs", "api");
fs.mkdirSync(out, { recursive: true });
const lf = (s) => s.replace(/\r\n/g, "\n");
const write = (name, text) => fs.writeFileSync(path.join(out, name), lf(text).replace(/\n+$/, "\n"));

function skip(name, why) {
  console.warn(`skipped ${name}: ${why}`);
  if (!fs.existsSync(path.join(out, name))) write(name, `# ${name}\n\nNot generated yet: ${why.split("\n")[0]}\n`);
}

// ---------- JS ----------
function buildJs() {
  const pkg = path.join(root, "clients", "js", "packages", "client");
  const tsc = path.join(root, "clients", "js", "node_modules", "typescript", "bin", "tsc");
  if (!fs.existsSync(path.join(pkg, "src", "index.ts")) || !fs.existsSync(tsc)) {
    return skip("js.md", "clients/js has no src/index.ts yet");
  }
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "ka-dts-"));
  try {
    execFileSync(process.execPath, [tsc, "-p", path.join(pkg, "tsconfig.build.json"), "--outDir", tmp,
      "--emitDeclarationOnly", "--declaration", "--sourceMap", "false", "--noEmit", "false"], { stdio: "pipe" });
  } catch (e) {
    if (!fs.existsSync(path.join(tmp, "index.d.ts"))) {
      return skip("js.md", "clients/js does not compile yet:\n" + ((e.stdout?.toString() ?? "")).slice(0, 400));
    }
  }
  const files = fs.readdirSync(tmp).filter((f) => f.endsWith(".d.ts")).sort();
  const read = (f) => lf(fs.readFileSync(path.join(tmp, f), "utf8")).replace(/\n+$/, "");
  const idx = read("index.d.ts");
  const mods = [...idx.matchAll(/from\s+["']\.\/([\w-]+)\.js["']/g)].map((m) => m[1] + ".d.ts").filter((f) => files.includes(f));
  const order = ["index.d.ts", ...[...new Set(mods)].filter((f) => f !== "index.d.ts")];
  let md = "# JS API reference: `@keepalive/client`\n\n"
    + "Generated by `node docs/build.mjs` from the package's `.d.ts`. Do not edit. `index` is the public entry; the other\n"
    + "sections are the modules it re-exports.\n";
  for (const f of order) md += `\n## ${f.replace(/\.d\.ts$/, "")}\n\n\`\`\`ts\n${read(f)}\n\`\`\`\n`;
  fs.rmSync(tmp, { recursive: true, force: true });
  write("js.md", md);
  console.log(`docs/api/js.md: ${order.length} modules`);
}

// ---------- .NET: a small cursor parser for public declarations ----------
function* csFiles(dir) {
  if (!fs.existsSync(dir)) return;
  const items = fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1));
  for (const e of items) {
    if (["bin", "obj", "node_modules"].includes(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) yield* csFiles(p);
    else if (e.name.endsWith(".cs")) yield p;
  }
}

function summaryOf(doc) {
  const s = doc.join(" ");
  const m = /<summary>([\s\S]*?)<\/summary>/.exec(s);
  return (m ? m[1] : "").replace(/<(?:see|paramref)\s+(?:cref|name)="([^"]+)"\s*\/>/g, (_, x) => x.replace(/^[A-Z]:/, "")).replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();
}

function scanCs(src) {
  const t = lf(src);
  let pos = 0;
  const entries = [];
  const scopes = []; // { visible, iface }
  let doc = [];

  const skipString = () => { // at a quote
    const q = t[pos++];
    while (pos < t.length && t[pos] !== q) { if (t[pos] === "\\") pos++; pos++; }
    pos++;
  };
  const skipTrivia = () => {
    for (;;) {
      while (pos < t.length && /\s/.test(t[pos])) pos++;
      if (t.startsWith("///", pos)) { const e = t.indexOf("\n", pos); doc.push(t.slice(pos + 3, e < 0 ? t.length : e).trim()); pos = e < 0 ? t.length : e; continue; }
      if (t.startsWith("//", pos)) { const e = t.indexOf("\n", pos); pos = e < 0 ? t.length : e; continue; }
      if (t.startsWith("/*", pos)) { const e = t.indexOf("*/", pos); pos = e < 0 ? t.length : e + 2; continue; }
      if (t[pos] === "#") { const e = t.indexOf("\n", pos); pos = e < 0 ? t.length : e; continue; }
      if (t[pos] === "[") { // attribute
        let d = 0;
        for (; pos < t.length; pos++) { if (t[pos] === "[") d++; else if (t[pos] === "]" && --d === 0) { pos++; break; } else if (t[pos] === '"') { skipString(); pos--; } }
        continue;
      }
      return;
    }
  };
  // Read a declaration head up to a top-level { ; => or = ; returns [text, terminator].
  const readHead = () => {
    const start = pos;
    let d = 0;
    while (pos < t.length) {
      const c = t[pos];
      if (c === '"' || c === "'") { skipString(); continue; }
      if (c === "(" || c === "[") d++;
      else if (c === ")" || c === "]") d--;
      else if (d === 0 && c === "{") { const h = t.slice(start, pos); pos++; return [h, "{"]; }
      else if (d === 0 && c === ";") { const h = t.slice(start, pos); pos++; return [h, ";"]; }
      else if (d === 0 && c === "=" && t[pos + 1] === ">") { const h = t.slice(start, pos); pos += 2; return [h, "=>"]; }
      else if (d === 0 && c === "=" && !"=!<>".includes(t[pos - 1]) && t[pos + 1] !== "=") { const h = t.slice(start, pos); pos++; return [h, "="]; }
      pos++;
    }
    return [t.slice(start), ""];
  };
  // After an opening { was consumed: return the inner text and move past the matching }.
  const readBlock = () => {
    const start = pos;
    let d = 1;
    while (pos < t.length && d > 0) {
      const c = t[pos];
      if (c === '"' || c === "'") { skipString(); continue; }
      if (t.startsWith("//", pos)) { const e = t.indexOf("\n", pos); pos = e < 0 ? t.length : e; continue; }
      if (c === "{") d++; else if (c === "}") d--;
      pos++;
    }
    return t.slice(start, pos - 1);
  };
  const skipToSemicolon = () => {
    let d = 0;
    while (pos < t.length) {
      const c = t[pos];
      if (c === '"' || c === "'") { skipString(); continue; }
      if (c === "(" || c === "{" || c === "[") d++;
      else if (c === ")" || c === "}" || c === "]") d--;
      else if (c === ";" && d <= 0) { pos++; return; }
      pos++;
    }
  };
  const accessorsOf = (body) => {
    const parts = [];
    let d = 0, cur = "";
    for (let i = 0; i < body.length; i++) {
      const c = body[i];
      if (c === "{") { if (d === 0) { parts.push(cur.trim()); cur = ""; } d++; }
      else if (c === "}") d--;
      else if (d === 0 && c === ";") { parts.push(cur.trim()); cur = ""; }
      else if (d === 0) cur += c;
    }
    return parts.filter(Boolean).map((p) => p.replace(/\s+/g, " ") + ";").join(" ");
  };

  const kindRe = /(?:^|\s)(class|struct|interface|enum|record|delegate)\s/;
  for (;;) {
    skipTrivia();
    if (pos >= t.length) break;
    if (t[pos] === "}") { pos++; scopes.pop(); doc = []; continue; }
    if (t[pos] === ";") { pos++; continue; }
    const myDoc = doc; doc = [];
    const [rawHead, term] = readHead();
    const head = rawHead.replace(/\s+/g, " ").replace(/\(\s+/g, "(").trim();
    const ind = "    ".repeat(scopes.filter((x) => !x.ns).length);
    if (!head && term !== "{") continue;
    const parent = scopes[scopes.length - 1];
    const visibleHere = scopes.every((s) => s.visible);
    if (/^(namespace|using|extern)\b/.test(head)) { if (term === "{") scopes.push({ visible: true, iface: false, ns: true }); continue; }
    const pre = head.split("(")[0] + " ";
    const km = kindRe.exec(pre);
    const modPublic = /^(public|protected)\b/.test(head) || (parent?.iface && !/^(private|internal)\b/.test(head));
    const emit = visibleHere && modPublic;
    const isType = !!km;
    if (isType) {
      const kind = km[1];
      if (term === "{" && kind === "enum") {
        const inner = readBlock().replace(/\s+/g, " ").trim();
        if (emit) entries.push({ ind, sig: `${head} { ${inner} }`, summary: summaryOf(myDoc) });
      } else if (term === "{") {
        if (emit) entries.push({ ind, sig: head, summary: summaryOf(myDoc) });
        scopes.push({ visible: emit, iface: kind === "interface" });
      } else {
        if (term === "=>" || term === "=") skipToSemicolon();
        if (emit) entries.push({ ind, sig: head + ";", summary: summaryOf(myDoc) });
      }
      continue;
    }
    // members
    if (term === "{") {
      const body = readBlock();
      if (emit) {
        // method/ctor bodies contain statements; property bodies are accessor lists. A head with "(" is a method/ctor.
        const sig = head.includes("(") && !/\)\s*$/.test(head) ? head : head;
        const isProp = !/\)\s*(where\b.*)?$/.test(head) && !head.includes("(");
        entries.push({ ind, sig: isProp ? `${head} { ${accessorsOf(body)} }` : head + ";", summary: summaryOf(myDoc) });
      }
    } else if (term === "=>" || term === "=") {
      skipToSemicolon();
      if (emit) entries.push({ ind, sig: head + ";", summary: summaryOf(myDoc) });
    } else if (term === ";") {
      if (emit) entries.push({ ind, sig: head + ";", summary: summaryOf(myDoc) });
    }
  }
  return entries;
}

function buildDotnet() {
  const base = path.join(root, "clients", "dotnet");
  const dirs = ["Keepalive.Core", "Keepalive.Godot"].map((d) => path.join(base, d));
  if (!fs.existsSync(dirs[0])) return skip("dotnet.md", "clients/dotnet not available");
  let md = "# .NET API reference: `Keepalive.Core` and `Keepalive.Godot`\n\n"
    + "Generated by `node docs/build.mjs` from the public declarations and `///` summaries. Do not edit.\n"
    + "Files with no public API are omitted.\n";
  let n = 0;
  for (const dir of dirs) {
    for (const f of csFiles(dir)) {
      const entries = scanCs(fs.readFileSync(f, "utf8"));
      if (!entries.length) continue;
      n += entries.length;
      md += `\n## ${path.relative(base, f).replace(/\\/g, "/")}\n\n\`\`\`csharp\n`;
      for (const e of entries) {
        if (e.summary) md += `${e.ind}/// ${e.summary}\n`;
        md += e.ind + e.sig + "\n";
      }
      md += "```\n";
    }
  }
  write("dotnet.md", md);
  console.log(`docs/api/dotnet.md: ${n} public declarations`);
}

buildJs();
buildDotnet();
