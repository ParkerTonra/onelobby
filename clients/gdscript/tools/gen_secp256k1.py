#!/usr/bin/env python3
"""Regenerates two things for the pure-GDScript secp256k1 used by Nostr signing:

  * the unrolled field multiply/square between the GENERATED markers in addons/onelobby/secp256k1.gd
  * the fixed-base comb table addons/onelobby/secp256k1_table.gd

Field elements are 10 little-endian limbs of 26 bits in a PackedInt64Array (GDScript ints are 64-bit signed, so a
26x26-bit product plus ten of them still fits). Run: python gen_secp256k1.py
"""
import base64
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ADDON = os.path.join(HERE, "..", "addons", "onelobby")

P = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEFFFFFC2F
GX = 0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798
GY = 0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8


def tail(var):
    """carry limbs 0..8 into 9, fold bits above 256 (2^256 = 2^32 + 977), settle limbs 0..2"""
    out = []
    for i in range(9):
        out.append(f"\t{var} = {var}{i} >> 26\n\t{var}{i} &= M\n\t{var}{i + 1} += {var}")
    # the carry variable is named `c`, limbs are c0..c9 (same prefix), so rename the scratch to avoid a clash
    return "\n".join(out)


def reduce_block():
    L = ["\tvar t := 0"]
    for k in range(18):
        L.append(f"\tt = c{k} >> 26\n\tc{k} &= M\n\tc{k + 1} += t")
    L.append("\tvar c19 := c18 >> 26\n\tc18 &= M")
    # fold c11..c19 first (never targets of a fold), then c10 which also received c19
    for k in range(11, 20):
        L.append(f"\tc{k - 10} += c{k} * 15632\n\tc{k - 9} += c{k} << 10")
    L.append("\tc0 += c10 * 15632\n\tc1 += c10 << 10")
    for i in range(9):
        L.append(f"\tt = c{i} >> 26\n\tc{i} &= M\n\tc{i + 1} += t")
    L.append("\tt = c9 >> 22\n\tc9 &= 0x3FFFFF\n\tc0 += t * 977\n\tc1 += t << 6")
    L.append("\tt = c0 >> 26\n\tc0 &= M\n\tc1 += t\n\tt = c1 >> 26\n\tc1 &= M\n\tc2 += t")
    L.append("\treturn PackedInt64Array([" + ", ".join(f"c{i}" for i in range(10)) + "])")
    return "\n".join(L)


def gen_mul():
    s = ["static func fe_mul(a: PackedInt64Array, b: PackedInt64Array) -> PackedInt64Array:"]
    for i in range(10):
        s.append(f"\tvar a{i}: int = a[{i}]")
    for i in range(10):
        s.append(f"\tvar b{i}: int = b[{i}]")
    for k in range(19):
        terms = [f"a{i} * b{k - i}" for i in range(10) if 0 <= k - i < 10]
        s.append(f"\tvar c{k}: int = " + " + ".join(terms))
    s.append(reduce_block())
    return "\n".join(s)


def gen_sqr():
    s = ["static func fe_sqr(a: PackedInt64Array) -> PackedInt64Array:"]
    for i in range(10):
        s.append(f"\tvar a{i}: int = a[{i}]")
    for i in range(9):
        s.append(f"\tvar d{i}: int = a{i} * 2")
    for k in range(19):
        terms = []
        for i in range(10):
            j = k - i
            if j < 0 or j > 9:
                continue
            if i < j:
                terms.append(f"d{i} * a{j}")
            elif i == j:
                terms.append(f"a{i} * a{i}")
        s.append(f"\tvar c{k}: int = " + " + ".join(terms))
    s.append(reduce_block())
    return "\n".join(s)


def add_pt(p, q):
    if p is None:
        return q
    if q is None:
        return p
    if p[0] == q[0]:
        if (p[1] + q[1]) % P == 0:
            return None
        lam = 3 * p[0] * p[0] * pow(2 * p[1], -1, P) % P
    else:
        lam = (q[1] - p[1]) * pow(q[0] - p[0], -1, P) % P
    x = (lam * lam - p[0] - q[0]) % P
    return (x, (lam * (p[0] - x) - p[1]) % P)


def comb_windows():
    base = (GX, GY)
    rows = []
    for _ in range(64):
        pts = []
        acc = None
        for _j in range(1, 16):
            acc = add_pt(acc, base)
            pts.append(acc)
        rows.append(b"".join(x.to_bytes(32, "big") + y.to_bytes(32, "big") for x, y in pts))
        for _ in range(4):
            base = add_pt(base, base)
    return rows


def main():
    gen = gen_mul() + "\n\n\n" + gen_sqr() + "\n"
    path = os.path.join(ADDON, "secp256k1.gd")
    with open(path, encoding="utf-8") as f:
        src = f.read()
    new, n = re.subn(
        r"(# BEGIN GENERATED[^\n]*\n).*?(# END GENERATED)",
        lambda m: m.group(1) + gen + m.group(2),
        src,
        flags=re.S,
    )
    assert n == 1, "markers not found in secp256k1.gd"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(new)
    t = [
        "class_name OneLobbySecp256k1Table",
        "extends RefCounted",
        "## GENERATED by tools/gen_secp256k1.py: do not edit. WINDOWS[i] is base64 of the 15 affine points j * 16^i * G",
        "## (j = 1..15), each x || y as 32 big-endian bytes. Fixed-base multiplication of G is then 64 additions, no doublings.",
        "",
        "const WINDOWS := [",
    ]
    for r in comb_windows():
        t.append('\t"' + base64.b64encode(r).decode() + '",')
    t.append("]")
    with open(os.path.join(ADDON, "secp256k1_table.gd"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(t) + "\n")


main()
